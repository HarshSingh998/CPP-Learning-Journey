#include <iostream>
using namespace std;

int main() {

    for(int i = 1 ; i <= 100 ; i++){
        cout << i << endl;
    }




    for(int i = 100; i >= 1; i--){
        cout << i << endl;
    }




    for(int i = 0; i >= -10; i--){
        cout << i << endl;
    }




    for(int i = 1; i <= 50; i++){
        cout << i << " -> " << "Harsh Singh" << endl;
    }




    for(int i = 1; i <= 10; i++){
        cout << 7*i << endl;
    }




    for(char i = 'A'; i <= 'Z'; i++){
        cout << i << endl;
    }




    for(char i = 'a'; i <= 'z'; i++){
        cout << i << endl;
    }


    return 0;
}


