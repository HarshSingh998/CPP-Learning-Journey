
// Class - 6

#include <iostream>
using namespace std;

int main() {


    // Counting From 1 To 100
    for(int i = 1 ; i <= 100 ; i++){
        cout << i << endl;
    }



    // Counting From 100 To 1
    for(int i = 100; i >= 1; i--){
        cout << i << endl;
    }



    // Counting From 0 To -10
    for(int i = 0; i >= -10; i--){
        cout << i << endl;
    }



    // Print Your Name 50 Time
    for(int i = 1; i <= 50; i++){
        cout << i << " -> " << "Harsh Singh" << endl;
    }



    // Print A Table Of 7
    for(int i = 1; i <= 10; i++){
        cout << 7*i << endl;
    }



    // Print Alphabets In Uppercase
    for(char i = 'A'; i <= 'Z'; i++){
        cout << i << endl;
    }



    // Print Alphabets In Lowercase
    for(char i = 'a'; i <= 'z'; i++){
        cout << i << endl;
    }


    return 0;
}
